#!/usr/bin/env node
/**
 * Builds every file of the StudioFlow logo "Programm" (issue #62) from one geometry:
 *
 *   docs/brand/*.svg                    master SVGs (icon dark and light, the two small favicon cuts, the mark, the wordmark lockup)
 *   docs/assets/logo-*.svg              the files README.md shows (wordmark light and dark, the square mark)
 *   apps/studio/public/favicon.*        Regie favicon (SVG without the tally dot, ICO 16/32/48)
 *   apps/output/public/favicon.svg      output page favicon (the only place the logo appears there)
 *   apps/sender/public/**               favicon.ico, icons/icon.svg, apple-touch-icon.png, icon-192/512.png, icon-maskable-512.png
 *
 * The PNG and ICO files are rendered from the SVGs with the Chromium of Playwright (already a devDependency; run
 * `npx playwright install chromium` once if it is missing). Usage:
 *
 *   npm run brand            write everything
 *   npm run brand -- --svg   SVG files only (no browser)
 *
 * The geometry mirrors the reference in issue #62 on a 64 x 64 grid. The header mark of the Regie and of the sender is
 * inlined in `icon.component.ts` and `brand-mark.component.ts`; change it there too when you change the geometry here.
 * Colours are the tokens of DESIGN.md (dark theme and light theme). Small sizes follow the issue: no tally dot up to 32 px,
 * and only one chevron at 16 px.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FLOW_PATH, STUDIO_PATH } from './lib/brand-wordmark.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const svgOnly = process.argv.includes('--svg');

const THEMES = {
  dark: { tile: '#1b212b', ink: '#e6edf3', muted: '#8b949e', red: '#ff6a63' },
  light: { tile: '#f3f5f8', ink: '#17202b', muted: '#566170', red: '#b71c28' },
};

const NS = 'xmlns="http://www.w3.org/2000/svg"';
const stroke = (ink, width) =>
  `fill="none" stroke="${ink}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round"`;

/** The reference "App icon" (full size) and its small cuts. `bleed` fills the whole square (maskable, iOS). */
function icon(theme, { size = 'full', bleed = false, scale = 1 } = {}) {
  const { tile, ink, muted, red } = THEMES[theme];
  const rx = bleed ? 0 : size === 'full' ? 14 : size === '32' ? 12 : 10;
  const head = `<svg ${NS} viewBox="0 0 64 64">\n  <rect width="64" height="64" rx="${rx}" fill="${tile}"/>`;
  let body;
  if (size === '16') {
    body = [
      `<rect x="8" y="14" width="48" height="36" rx="6" fill="none" stroke="${ink}" stroke-width="7"/>`,
      `<path d="M24 24l8 8-8 8" ${stroke(ink, 7)}/>`,
    ];
  } else if (size === '32') {
    body = [
      `<rect x="8" y="14" width="48" height="34" rx="5" fill="none" stroke="${ink}" stroke-width="5"/>`,
      `<path d="M22 24l7 7-7 7M33 24l7 7-7 7" ${stroke(ink, 5)}/>`,
    ];
  } else {
    body = [
      `<rect x="8" y="14" width="48" height="32" rx="5" fill="none" stroke="${ink}" stroke-width="3.5"/>`,
      `<path d="M22 23l7 7-7 7M32 23l7 7-7 7" ${stroke(ink, 3.5)}/>`,
      `<circle cx="48" cy="22" r="3" fill="${red}"/>`,
      `<rect x="24" y="51" width="16" height="3.5" rx="1.75" fill="${muted}"/>`,
    ];
  }
  const inner = body.map((line) => `    ${line}`).join('\n');
  const content =
    scale === 1
      ? body.map((line) => `  ${line}`).join('\n')
      : `  <g transform="translate(${(32 * (1 - scale)).toFixed(2)} ${(32 * (1 - scale)).toFixed(2)}) scale(${scale})">\n${inner}\n  </g>`;
  return `${head}\n${content}\n</svg>\n`;
}

/** Header mark: no tile, `currentColor`, the tally dot follows the `--red` token (falls back to the dark value). */
const MARK_BODY = [
  `<rect x="6" y="14" width="52" height="36" rx="6" fill="none" stroke="currentColor" stroke-width="4.5"/>`,
  `<path d="M21 24l8 8-8 8M33 24l8 8-8 8" ${stroke('currentColor', 4.5)}/>`,
  `<circle cx="49" cy="23" r="3.5" fill="var(--red, #ff6a63)"/>`,
];
const mark = () => `<svg ${NS} viewBox="0 0 64 64">\n${MARK_BODY.map((l) => `  ${l}`).join('\n')}\n</svg>\n`;

/** Wordmark lockup: the mark with a fixed colour, "Studio" in text, "Flow" in muted. Outlined, so no font is needed. */
function wordmark(theme) {
  const { ink, muted, red } = THEMES[theme];
  return `<svg ${NS} viewBox="0 0 300 60" width="300" height="60" role="img" aria-label="StudioFlow">
  <title>StudioFlow</title>
  <!-- Logo "Programm" for ${theme === 'dark' ? 'dark' : 'light'} backgrounds (transparent background): the 16:9 program frame, two flow chevrons and the tally dot, then the name in
       Sofia Sans Semi Condensed Bold (SIL Open Font License 1.1, see THIRD_PARTY_NOTICES.md) converted to outlines so that no font is needed.
       Generated by tools/build-brand.mjs. -->
  <g transform="translate(0.8 1.4) scale(0.85)">
    <rect x="6" y="14" width="52" height="36" rx="6" fill="none" stroke="${ink}" stroke-width="4.5"/>
    <path d="M21 24l8 8-8 8M33 24l8 8-8 8" ${stroke(ink, 4.5)}/>
    <circle cx="49" cy="23" r="3.5" fill="${red}"/>
  </g>
  <g transform="translate(68 45.72)">
    <path fill="${ink}" d="${STUDIO_PATH}"/>
    <path fill="${muted}" d="${FLOW_PATH}"/>
  </g>
</svg>
`;
}

/** The icon with a title, for a standalone file that has an accessible name. */
const named = (svg) =>
  svg.replace(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">',
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="StudioFlow">\n  <title>StudioFlow</title>',
  );

const files = new Map();
const put = (path, content) => files.set(path, content);

const master = {
  'icon-dark.svg': named(icon('dark')),
  'icon-light.svg': named(icon('light')),
  'favicon-32-dark.svg': named(icon('dark', { size: '32' })),
  'favicon-16-dark.svg': named(icon('dark', { size: '16' })),
  'mark.svg': mark(),
  'wordmark-dark.svg': wordmark('dark'),
  'wordmark-light.svg': wordmark('light'),
};
for (const [name, content] of Object.entries(master)) {
  put(`docs/brand/${name}`, content);
}
put('docs/assets/logo-dark.svg', master['wordmark-dark.svg']);
put('docs/assets/logo-light.svg', master['wordmark-light.svg']);
put('docs/assets/logo-mark.svg', master['icon-dark.svg']);
put('apps/studio/public/favicon.svg', master['favicon-32-dark.svg']);
put('apps/output/public/favicon.svg', master['favicon-32-dark.svg']);
put('apps/sender/public/icons/icon.svg', master['icon-dark.svg']);

for (const [path, content] of files) {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  console.log(`wrote ${path}`);
}

if (svgOnly) {
  process.exit(0);
}

// --- raster files ---------------------------------------------------------------------------------------------------
const { chromium } = await import('@playwright/test');

/** ICO container with PNG images (Vista and later, every browser). */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, png }, i) => {
    const at = 6 + 16 * i;
    header.writeUInt8(size, at);
    header.writeUInt8(size, at + 1);
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(png.length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += png.length;
  });
  return Buffer.concat([header, ...images.map(({ png }) => png)]);
}

const browser = await chromium.launch();
const page = await browser.newPage();
async function png(svg, size) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(
    `<!doctype html><style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${svg}`,
  );
  return page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
}
const out = (path, buffer) => {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, buffer);
  console.log(`wrote ${path} (${buffer.length} bytes)`);
};

const faviconIco = ico([
  { size: 16, png: await png(icon('dark', { size: '16' }), 16) },
  { size: 32, png: await png(icon('dark', { size: '32' }), 32) },
  { size: 48, png: await png(icon('dark'), 48) },
]);
out('apps/studio/public/favicon.ico', faviconIco);
out('apps/sender/public/favicon.ico', faviconIco);
out('apps/sender/public/icons/apple-touch-icon.png', await png(icon('dark', { bleed: true }), 180));
out('apps/sender/public/icons/icon-192.png', await png(icon('dark'), 192));
out('apps/sender/public/icons/icon-512.png', await png(icon('dark'), 512));
// Maskable: the content stays inside the central 80 % circle (safe zone); 0.72 leaves a margin for the frame corners.
out('apps/sender/public/icons/icon-maskable-512.png', await png(icon('dark', { bleed: true, scale: 0.72 }), 512));
await browser.close();
