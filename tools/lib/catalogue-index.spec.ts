import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  camelCase,
  listNamespaces,
  namespacePrefix,
  renderIndex,
  syncIndexes,
} from './catalogue-index.mjs';
import { evaluateCatalogueSource, loadCatalogues } from './catalogue-files.mjs';

function messagesDirectory(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'messages-'));
  for (const locale of ['en', 'de-CH']) {
    mkdirSync(join(root, locale));
  }
  for (const [path, content] of Object.entries(files)) {
    writeFileSync(join(root, path), content);
  }
  return root;
}

describe('names', () => {
  it('turns file names into export names and prefixes', () => {
    expect(camelCase('regie-scenes')).toBe('regieScenes');
    expect(camelCase('sender-camera-problem')).toBe('senderCameraProblem');
    expect(camelCase('common')).toBe('common');
    expect(camelCase('de-CH')).toBe('deCH');
    expect(namespacePrefix('regie-scenes')).toBe('regie.scenes');
    expect(namespacePrefix('common')).toBe('common');
  });
});

describe('renderIndex', () => {
  it('writes sorted one-per-line imports and one spread object for English', () => {
    expect(renderIndex('en', ['a-b', 'common'])).toBe(
      [
        '// Generated by tools/i18n-index.mjs (npm run i18n:index). Do not edit by hand.',
        "import { aB } from './a-b';",
        "import { common } from './common';",
        '',
        'export const en = {',
        '  ...aB,',
        '  ...common,',
        '} as const;',
        '',
      ].join('\n'),
    );
  });

  it('annotates every other locale against the English type', () => {
    const text = renderIndex('de-CH', ['common']);
    expect(text).toContain("import type { en } from '../en';");
    expect(text).toContain('export const deCH: Translation<typeof en> = {');
  });
});

describe('syncIndexes', () => {
  const english = "export const common = { 'common.ok': 'OK' } as const;";
  const german = "export const common = { 'common.ok': 'OK' };";

  it('writes the indexes of both locales and then finds them current', () => {
    const root = messagesDirectory({ 'en/common.ts': english, 'de-CH/common.ts': german });
    try {
      const first = syncIndexes(root, { check: false });
      expect(first.problems).toEqual([]);
      expect(first.written).toEqual(['messages/en/index.ts', 'messages/de-CH/index.ts']);
      expect(readFileSync(join(root, 'en', 'index.ts'), 'utf8')).toContain('...common');
      expect(syncIndexes(root, { check: true }).problems).toEqual([]);
      expect(syncIndexes(root, { check: false }).written).toEqual([]);
    } finally {
      rmSync(root, { recursive: true });
    }
  });

  it('reports a missing, stale or merge-damaged index in check mode', () => {
    const root = messagesDirectory({ 'en/common.ts': english, 'de-CH/common.ts': german });
    try {
      expect(syncIndexes(root, { check: true }).problems).toHaveLength(2);
      syncIndexes(root, { check: false });
      writeFileSync(join(root, 'en', 'extra.ts'), english);
      writeFileSync(join(root, 'de-CH', 'extra.ts'), german);
      expect(syncIndexes(root, { check: true }).problems.join('\n')).toContain('stale');
      syncIndexes(root, { check: false });
      const damaged = readFileSync(join(root, 'en', 'index.ts'), 'utf8').replace(
        "import { common } from './common';\n",
        "import { common } from './common';\nimport { common } from './common';\n",
      );
      writeFileSync(join(root, 'en', 'index.ts'), damaged);
      expect(syncIndexes(root, { check: true }).problems.join('\n')).toContain('stale or damaged');
    } finally {
      rmSync(root, { recursive: true });
    }
  });

  it('requires the same files in every locale', () => {
    const root = messagesDirectory({
      'en/common.ts': english,
      'en/only-en.ts': english,
      'de-CH/common.ts': german,
      'de-CH/only-de.ts': german,
    });
    try {
      const problems = syncIndexes(root, { check: true }).problems.join('\n');
      expect(problems).toContain('de-CH/only-en.ts is missing');
      expect(problems).toContain('de-CH/only-de.ts has no English counterpart');
    } finally {
      rmSync(root, { recursive: true });
    }
  });

  it('lists namespaces without the index and spec files', () => {
    const root = messagesDirectory({
      'en/b.ts': '',
      'en/a.ts': '',
      'en/index.ts': '',
      'en/a.spec.ts': '',
    });
    try {
      expect(listNamespaces(join(root, 'en'))).toEqual(['a', 'b']);
      expect(listNamespaces(join(root, 'missing'))).toEqual([]);
    } finally {
      rmSync(root, { recursive: true });
    }
  });
});

describe('loading catalogues', () => {
  it('evaluates a catalogue file that only imports types', () => {
    const messages = evaluateCatalogueSource(
      "import type { Namespace } from '../../types';\nexport const x = { 'x.a': 'A', 'x.n': { one: '1', other: '2' } } as const satisfies Namespace<'x'>;",
    );
    expect(messages).toEqual({ 'x.a': 'A', 'x.n': { one: '1', other: '2' } });
  });

  it('rejects a file that exports more than one object', () => {
    expect(() => evaluateCatalogueSource('export const a = {}; export const b = {};')).toThrow();
  });

  it('loads the real catalogues of the repository', () => {
    const catalogues = loadCatalogues(join(process.cwd(), 'packages/i18n/src/messages'));
    expect([...catalogues.keys()]).toEqual(['en', 'de-CH']);
    expect(catalogues.get('en')?.get('common')?.prefix).toBe('common');
    expect(catalogues.get('en')?.get('regie-scenes')?.prefix).toBe('regie.scenes');
    expect(catalogues.get('en')?.get('common')?.messages).toHaveProperty(['common.ok']);
  });
});
